#!/usr/bin/env python3
"""One-command setup for the device lifecycle portal demo.

  python setup/setup.py build --profile <PROFILE> --catalog <CATALOG> --warehouse <WAREHOUSE_ID>
      Generates the synthetic data (~262K device records, ~85K repairs), the per-customer governed views,
      the verify functions, three Genie spaces and three AI/BI dashboards, then writes the app config.

  cd app && databricks apps deploy --profile <PROFILE>

  python setup/setup.py grant --profile <PROFILE> --catalog <CATALOG> --app-name <APP_NAME>
      After the first deploy: grants the app's service principal read access and adds the app's domain
      to the AI/BI dashboard embedding allow list (additive, existing domains are kept).

All data is synthetic and fictional. Requires the Databricks CLI (v1.0+) authenticated to the workspace.
"""
import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
APP = os.path.join(ROOT, 'app')
sys.path.insert(0, HERE)


def cli(args, profile, check=True):
    r = subprocess.run(['databricks', *args, '--profile', profile], capture_output=True, text=True)
    if check and r.returncode:
        raise RuntimeError(f"databricks {' '.join(args[:3])} failed: {r.stderr.strip()[:800]}")
    return r


def run_sql(stmt, profile, warehouse):
    r = subprocess.run(['databricks', 'experimental', 'aitools', 'tools', 'query', '--profile', profile,
                        '--warehouse', warehouse, '--output', 'json', stmt], capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(f'SQL failed: {stmt[:120]}...\n{(r.stderr or r.stdout).strip()[:800]}')
    return r.stdout


def schemas(catalog, prefix):
    return {
        'data': f'{catalog}.{prefix}device_demo',
        'northwind': f'{catalog}.{prefix}portal_northwind',
        'bastion': f'{catalog}.{prefix}portal_bastion',
    }


def build(a):
    s = schemas(a.catalog, a.prefix)
    sub = {'{{DATA}}': s['data'], '{{NW}}': s['northwind'], '{{BA}}': s['bastion']}
    sql_dir = os.path.join(HERE, 'sql')
    print(f"1/5 Data in {s['data']} (+ governed views in {s['northwind']}, {s['bastion']})")
    for f in sorted(os.listdir(sql_dir)):
        if not f.endswith('.sql'):
            continue
        text = open(os.path.join(sql_dir, f)).read()
        for k, v in sub.items():
            text = text.replace(k, v)
        stmts = [x.strip() for x in text.split(';\n') if x.strip()] if f[:2] in ('09', '10', '11') else [text.strip()]
        print(f'  {f} ({len(stmts)} statement{"s" if len(stmts) > 1 else ""})')
        for st in stmts:
            run_sql(st, a.profile, a.warehouse)
        if f.startswith('08'):
            run_sql(f"DROP TABLE IF EXISTS {s['data']}._gen_stage", a.profile, a.warehouse)
    run_sql(f"DROP TABLE IF EXISTS {s['data']}._gen_models", a.profile, a.warehouse)

    print('2/5 Genie spaces')
    from build_spaces import create_spaces
    genie = create_spaces(a.profile, a.warehouse, s['data'], s['northwind'], s['bastion'])

    print('3/5 AI/BI dashboards')
    from build_dashboards import create_dashboards
    me = json.loads(cli(['current-user', 'me', '-o', 'json'], a.profile).stdout)['userName']
    parent = a.parent_path or f'/Workspace/Users/{me}/device-lifecycle-portal-demo'
    dash = create_dashboards(a.profile, a.warehouse, a.catalog,
                             {'ops': s['data'].split('.', 1)[1], 'northwind': s['northwind'].split('.', 1)[1],
                              'bastion': s['bastion'].split('.', 1)[1]}, parent)

    print('4/5 App config')
    host = json.loads(cli(['auth', 'describe', '-o', 'json'], a.profile).stdout)['details']['host'].rstrip('/')
    ws_id = str(json.loads(cli(['api', 'get', '/api/2.1/unity-catalog/current-metastore-assignment'], a.profile).stdout)['workspace_id'])
    write_app_config(a, s, genie, dash, host, ws_id)

    print('5/5 Done.\n')
    print('Next:')
    print(f'  cd app && npm install && databricks apps deploy --profile {a.profile}')
    print(f'  python setup/setup.py grant --profile {a.profile} --catalog {a.catalog} --prefix "{a.prefix}" --app-name {a.app_name}')


def write_app_config(a, s, genie, dash, host, ws_id):
    cfg = f"""// Generated by setup/setup.py. Re-run setup to regenerate.
export const WORKSPACE_HOST = '{host}';
export const WORKSPACE_ID = '{ws_id}';
export const SCHEMAS = {{ ops: '{s['data']}', northwind: '{s['northwind']}', bastion: '{s['bastion']}' }};
export const DASHBOARDS = {{ ops: '{dash['ops']}', northwind: '{dash['northwind']}', bastion: '{dash['bastion']}' }};
export const VERIFY_FUNCTION = '{s['data']}.verify_devices()';
"""
    open(os.path.join(APP, 'client', 'src', 'config.generated.ts'), 'w').write(cfg)
    qdir = os.path.join(APP, 'config', 'queries')
    for f in os.listdir(qdir):
        p = os.path.join(qdir, f)
        t = open(p).read()
        if '__DATA_SCHEMA__' in t:
            open(p, 'w').write(t.replace('__DATA_SCHEMA__', s['data']))
    yml = f"""bundle:
  name: {a.app_name}

variables:
  sql_warehouse_id:
    description: SQL Warehouse ID
  genie_space_ops:
    description: Genie space for the operations view
  genie_space_northwind:
    description: Genie space for the Northwind Mobile portal
  genie_space_bastion:
    description: Genie space for the Bastion Protect portal

resources:
  apps:
    app:
      name: "{a.app_name}"
      description: "White-labeled device lifecycle portal demo (Databricks Apps + AI/BI + Genie + Unity Catalog)"
      source_code_path: ./
      lifecycle:
        started: true
      user_api_scopes:
        - dashboards.genie
      resources:
        - name: sql-warehouse
          sql_warehouse:
            id: ${{var.sql_warehouse_id}}
            permission: CAN_USE
        - name: genie-space
          genie_space:
            name: Device Intelligence (Operations)
            space_id: ${{var.genie_space_ops}}
            permission: CAN_RUN
        - name: genie-space-northwind
          genie_space:
            name: Northwind Mobile Device Returns Assistant
            space_id: ${{var.genie_space_northwind}}
            permission: CAN_RUN
        - name: genie-space-bastion
          genie_space:
            name: Bastion Protect Claims Device Assistant
            space_id: ${{var.genie_space_bastion}}
            permission: CAN_RUN

targets:
  default:
    default: true
    workspace:
      host: {host}
    variables:
      sql_warehouse_id: {a.warehouse}
      genie_space_ops: {genie['ops']}
      genie_space_northwind: {genie['northwind']}
      genie_space_bastion: {genie['bastion']}
"""
    open(os.path.join(APP, 'databricks.yml'), 'w').write(yml)
    env = f"""DATABRICKS_CONFIG_PROFILE={a.profile}
DATABRICKS_WAREHOUSE_ID={a.warehouse}
DATABRICKS_GENIE_SPACE_ID={genie['ops']}
GENIE_SPACE_OPS={genie['ops']}
GENIE_SPACE_NORTHWIND={genie['northwind']}
GENIE_SPACE_BASTION={genie['bastion']}
DATABRICKS_APP_PORT=8000
DATABRICKS_APP_NAME={a.app_name}
FLASK_RUN_HOST=0.0.0.0
"""
    open(os.path.join(APP, '.env'), 'w').write(env)
    print('  wrote app/client/src/config.generated.ts, app/databricks.yml, app/.env, config/queries')


def grant(a):
    s = schemas(a.catalog, a.prefix)
    app = json.loads(cli(['apps', 'get', a.app_name, '-o', 'json'], a.profile).stdout)
    sp = app['service_principal_client_id']
    url = app['url'].replace('https://', '').rstrip('/')
    print(f'Granting {sp} ({a.app_name}) read access')
    wh = a.warehouse or json.loads(cli(['experimental', 'aitools', 'tools', 'get-default-warehouse', '-o', 'json'], a.profile).stdout).get('id')
    for st in [f'GRANT USE CATALOG ON CATALOG {a.catalog} TO `{sp}`',
               f"GRANT USE SCHEMA, SELECT, EXECUTE ON SCHEMA {s['data']} TO `{sp}`",
               f"GRANT USE SCHEMA, SELECT ON SCHEMA {s['northwind']} TO `{sp}`",
               f"GRANT USE SCHEMA, SELECT ON SCHEMA {s['bastion']} TO `{sp}`"]:
        run_sql(st, a.profile, wh)
    cur = json.loads(cli(['settings', 'aibi-dashboard-embedding-approved-domains', 'get', '-o', 'json'], a.profile).stdout)
    domains = cur.get('aibi_dashboard_embedding_approved_domains', {}).get('approved_domains', []) or []
    if url not in domains:
        domains = domains + [url]
        body = {'allow_missing': True, 'field_mask': 'aibi_dashboard_embedding_approved_domains.approved_domains',
                'setting': {'aibi_dashboard_embedding_approved_domains': {'approved_domains': domains}}}
        cli(['settings', 'aibi-dashboard-embedding-approved-domains', 'update', '--json', json.dumps(body)], a.profile)
        print(f'Added {url} to the dashboard embedding allow list (kept {len(domains) - 1} existing)')
    print('Done. Note: the embedding access policy must allow approved domains '
          '(databricks settings aibi-dashboard-embedding-access-policy get).')


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('command', choices=['build', 'grant'])
    p.add_argument('--profile', required=True)
    p.add_argument('--catalog', required=True)
    p.add_argument('--warehouse', help='SQL warehouse ID (Pro or Serverless; AI_FORECAST needs serverless)')
    p.add_argument('--prefix', default='', help='Optional schema prefix, e.g. "demo_" to keep several copies apart')
    p.add_argument('--app-name', default='device-lifecycle-portal')
    p.add_argument('--parent-path', help='Workspace folder for the dashboards')
    a = p.parse_args()
    if a.command == 'build':
        if not a.warehouse:
            p.error('--warehouse is required for build')
        build(a)
    else:
        grant(a)


if __name__ == '__main__':
    main()
